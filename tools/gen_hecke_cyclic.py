def dim2_block(w):
    kk = f"HeckeCyclicWeight{w}"
    return f"""/-! ### Weight {w} (dim 2) -/
namespace {kk}

/-- **`𝕋 = ℤ[T₂]` at weight {w}**: both lattices are `span ℤ {{1, T₂}}`. -/
theorem heckeLattice_eq_t2Span :
    heckeLattice (({w} : ℕ) : ℤ) 2
      = HeckeCyclic.t2Span HeckeRatWeight{w}.T2 2 :=
  HeckeCyclic.heckeLattice_eq_t2Span_two _
    (heckeTM_prime _ Nat.prime_two).symm

end {kk}
"""


def dim34_block(w, n):
    kk = f"HeckeCyclicWeight{w}"
    arms = "\n".join(
        f"  | {j}, _, m => ⟨_, MaedaT3Weight{w}.c{j + 1} m⟩" for j in range(n)
    )
    # the impossibility arm: i ≥ n
    imp = f"  | _ + {n}, h, _ => absurd h (by omega)"
    miller = f"MaedaT3Weight{w}.fb MaedaT3Weight{w}.Atab"
    hzero = f"MaedaT3Weight{w}.hzero MaedaT3Weight{w}.hone MaedaT3Weight{w}.hA"
    hcard_type = (
        f"Nat.card ((heckeLattice (({w} : ℕ) : ℤ) {n}).toAddSubgroup ⧸\n"
        f"      (HeckeCyclic.t2Span HeckeRatWeight{w}.T2 {n}).toAddSubgroup.addSubgroupOf\n"
        f"        (heckeLattice (({w} : ℕ) : ℤ) {n}).toAddSubgroup)\n"
        f"      = (HeckeIndexWeight{w}.Ik).natAbs"
    )
    return f"""/-! ### Weight {w} (dim {n}) -/
namespace {kk}

/-- The echelon basis at weight {w} has integer `q`-coefficients (all `m`). -/
theorem hfi : ∀ i : ℕ, i < {n} → ∀ m : ℕ,
    ∃ z : ℤ, (qExpansion 1 (MaedaT3Weight{w}.fb i)).coeff m = (z : ℂ)
{arms}
{imp}

/-- The witness identity `∑ cert_j T₂^j = D • T₃` at the operator level. -/
theorem op_id : ∑ j ∈ Finset.range {n}, ((HeckeRatWeight{w}.cert j : ℤ) : ℂ)
      • HeckeRatWeight{w}.T2 ^ j
    = ((HeckeIndexWeight{w}.Dn : ℤ) : ℂ) • MaedaT3Weight{w}.T3 :=
  int_poly_of_dimN (by norm_num) MaedaT3Weight{w}.finrank_eq MaedaT3Weight{w}.fb
    MaedaT3Weight{w}.Atab HeckeRatWeight{w}.Xtab2 MaedaT3Weight{w}.Xtab
    {hzero}
    HeckeRatWeight{w}.T2 MaedaT3Weight{w}.T3 HeckeRatWeight{w}.hX2 MaedaT3Weight{w}.hX
    HeckeRatWeight{w}.M2 MaedaT3Weight{w}.M HeckeRatWeight{w}.hM2 HeckeRatWeight{w}.hM3
    HeckeRatWeight{w}.cert HeckeIndexWeight{w}.Dn HeckeIndexWeight{w}.scaled_idN

/-- `D • T₃ ∈ ℤ[T₂]` — the witness kills the class of `T₃`. -/
theorem Dn_smul_mem : ((HeckeIndexWeight{w}.Dn : ℤ) : ℂ) • MaedaT3Weight{w}.T3
    ∈ HeckeCyclic.t2Span HeckeRatWeight{w}.T2 {n} := by
  rw [← op_id]
  refine Submodule.sum_mem _ fun j hj => ?_
  rw [Int.cast_smul_eq_zsmul ℂ]
  exact Submodule.smul_mem _ _
    (HeckeCyclic.pow_mem_t2Span _ _ (Finset.mem_range.mp hj))

/-- The index cardinality `[𝕋 : ℤ[T₂]] = |I_k|` at weight {w}: index-card's
`HeckeIndexCardWeight{w}.index_card_natCard`, with `heckeTM k 2 = T₂`
(`heckeTM_prime`; `t2Lattice` is `t2Span` by definition). -/
theorem index_card : {hcard_type} := by
  have h := HeckeIndexCardWeight{w}.index_card_natCard
  rw [heckeTM_prime _ Nat.prime_two] at h
  exact h

/-- **`D = I_k` at weight {w}**: the quotient `𝕋 ⧸ ℤ[T₂]` is generated by
`[T₃]` and killed by `D`, so `I_k ∣ D`; the landed `D ∣ I_k` and positivity
close the equality. -/
theorem D_eq_Ik :
    HeckeIndexWeight{w}.Dn = HeckeIndexWeight{w}.Ik :=
  HeckeCyclic.D_eq_Ik_of_cyclic (by norm_num) (by norm_num) (by norm_num)
    (miller {miller} {n})
    (miller_linearIndependent {miller}
      {hzero})
    MaedaT3Weight{w}.finrank_eq
    (fun j m hj hm => miller_coeff' {miller}
      {hzero} j m hj hm)
    (fun j m hj => miller_int {miller}
      MaedaT3Weight{w}.hA hfi j m hj)
    HeckeRatWeight{w}.T2 MaedaT3Weight{w}.T3
    (heckeTM_prime _ Nat.prime_two).symm (heckeTM_prime _ Nat.prime_three).symm
    HeckeIndexWeight{w}.Dn HeckeIndexWeight{w}.Ik
    (by norm_num [HeckeIndexWeight{w}.Dn]) (by norm_num [HeckeIndexWeight{w}.Ik])
    Dn_smul_mem HeckeIndexWeight{w}.D_dvd_Ik index_card

/-- `ℤ[T₂] ⊆ 𝕋` at weight {w} (the Miller bundle form). -/
theorem t2Span_le : HeckeCyclic.t2Span HeckeRatWeight{w}.T2 {n}
    ≤ heckeLattice (({w} : ℕ) : ℤ) {n} :=
  HeckeCyclic.t2Span_le_heckeLattice (miller {miller} {n})
    (by norm_num)
    (miller_linearIndependent {miller}
      {hzero})
    MaedaT3Weight{w}.finrank_eq
    (fun j m hj hm => miller_coeff' {miller}
      {hzero} j m hj hm)
    (fun j m hj => miller_int {miller}
      MaedaT3Weight{w}.hA hfi j m hj)
    (by norm_num) _ (heckeTM_prime _ Nat.prime_two).symm

/-- **`𝕋 ≠ ℤ[T₂]` at weight {w}**: the index `I_k ≠ 1` here, so the
quotient is nontrivial (via the iff and `index_card`). -/
theorem heckeLattice_ne_t2Span :
    heckeLattice (({w} : ℕ) : ℤ) {n} ≠ HeckeCyclic.t2Span HeckeRatWeight{w}.T2 {n} := by
  intro h
  have h1 := (HeckeCyclic.heckeLattice_eq_t2Span_iff _
    (HeckeIndexWeight{w}.Ik).natAbs t2Span_le index_card).mp h
  norm_num [HeckeIndexWeight{w}.Ik] at h1

end {kk}
"""


def main():
    check = "--check" in sys.argv
    body = [HEADER]
    for w, n in WEIGHTS:
        body.append(dim2_block(w) if n == 2 else dim34_block(w, n))
        body.append("\n")
    text = "".join(body)
    if check:
        committed = OUT.read_text()
        if committed != text:
            sys.exit("HeckeCyclicWeights.lean is stale; regenerate")
        print("check ok: byte-identical")
        return
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
