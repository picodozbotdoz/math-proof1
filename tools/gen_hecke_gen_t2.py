#!/usr/bin/env python3
"""Generate MathProof/ModularForms/HeckeGeneratedByT2Weights.lean.

One `heckeTP_mem_spanT2_weightKK` corollary per verified Maeda weight: for
every prime `p`, the Hecke operator `T_p` on `S_k(SL(2, ℤ))` is a polynomial
in `T₂` with complex coefficients (the level-one Hecke algebra is generated by
`T₂`).  Each instance is `HeckeGeneratedByT2.heckeTP_mem_spanT2` applied to
the weight's `charpoly_T2` and `maeda` theorems from the Maeda files.

Run from the repository root:
    python3 -I tools/gen_hecke_gen_t2.py            # write the file
    python3 -I tools/gen_hecke_gen_t2.py --check    # verify byte-identical

The weight table mirrors the namespaces of
MaedaWeight24 / MaedaSmallWeights / MaedaDim{4..10}Weights (54 weights,
every even weight 24..134, i.e. dim S_k in 2..10).
"""

import sys
from pathlib import Path

# (weight, namespace, charpoly theorem, maeda theorem, T₂ term)
WEIGHTS: list[tuple[int, str, str, str, str]] = [
    (24, "MaedaWeight24", "charpoly_heckeT2", "maeda_weight24", "MaedaWeight24.heckeT2"),
]
WEIGHTS += [
    (w, f"MaedaWeight{w}", "charpoly_T2", "maeda", f"MaedaWeight{w}.T2")
    for w in [28, 30, 32, 34, 36, 38, 40, 42, 44, 46, 50]
]
WEIGHTS += [
    (w, f"MaedaWeight{w}", "charpoly_T2", "maeda", f"MaedaWeight{w}.T2")
    for w in [
        48, 52, 54, 56, 58, 62,            # dim 4
        60, 64, 66, 68, 70, 74,            # dim 5
        72, 76, 78, 80, 82, 86,            # dim 6
        84, 88, 90, 92, 94, 98,            # dim 7
        96, 100, 102, 104, 106, 110,       # dim 8
        108, 112, 114, 116, 118, 122,      # dim 9
        120, 124, 126, 128, 130, 134,      # dim 10
    ]
]
WEIGHTS.sort()

HEADER = """import MathProof.ModularForms.HeckeGeneratedByT2
import MathProof.ModularForms.MaedaWeight24
import MathProof.ModularForms.MaedaSmallWeights
import MathProof.ModularForms.MaedaDim4Weights
import MathProof.ModularForms.MaedaDim5Weights
import MathProof.ModularForms.MaedaDim6Weights
import MathProof.ModularForms.MaedaDim7Weights
import MathProof.ModularForms.MaedaDim8Weights
import MathProof.ModularForms.MaedaDim9Weights
import MathProof.ModularForms.MaedaDim10Weights

/-!
# The Hecke algebra of `S_k(SL(2, ℤ))` is generated by `T₂`: the 54 instances

One corollary per verified Maeda weight (every even weight `24 ≤ k ≤ 134`,
i.e. `2 ≤ dim S_k ≤ 10`): for every prime `p` there is a polynomial `Q` over
`ℂ` with

    T_p = aeval T₂ Q   on  S_k(SL(2, ℤ)),

so the Hecke algebra of `S_k` is generated by `T₂` alone.  Each instance is
`HeckeGeneratedByT2.heckeTP_mem_spanT2` applied to the weight's characteristic
polynomial theorem and Maeda irreducibility theorem:

* weight 24: `MaedaWeight24.charpoly_heckeT2` + `MaedaWeight24.maeda_weight24`;
* dims 2-3: `MaedaSmallWeights` (11 weights);
* dims 4-10: `MaedaDim4Weights` … `MaedaDim10Weights` (42 weights).

Commutativity is `HeckeCommute.heckeTPₗ_commute`, packaged inside
`heckeTP_mem_spanT2`.

This file is generated by `tools/gen_hecke_gen_t2.py` — regenerate, never
hand-edit (`python3 -I tools/gen_hecke_gen_t2.py --check` verifies
byte-identity).
-/

open Polynomial MaedaLevelOne
open scoped MatrixGroups

namespace HeckeGeneratedByT2Weights

open UpperHalfPlane ModularForm CuspForm

variable {p : ℕ}

"""


def block(w: int, ns: str, charpoly: str, maeda: str, t2: str) -> str:
    return f"""/-- In weight {w}, every Hecke operator `T_p` is a polynomial in `T₂`. -/
theorem heckeTP_mem_spanT2_weight{w} (hp : p.Prime) :
    ∃ Q : ℂ[X], heckeTPₗ (({w} : ℕ) : ℤ) hp = Polynomial.aeval {t2} Q :=
  HeckeGeneratedByT2.heckeTP_mem_spanT2 {ns}.{charpoly} {ns}.{maeda}
    hp

"""


def generate() -> str:
    out = HEADER
    out += "".join(block(*entry) for entry in WEIGHTS)
    out += "end HeckeGeneratedByT2Weights\n"
    return out


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    target = root / "MathProof/ModularForms/HeckeGeneratedByT2Weights.lean"
    text = generate()
    for i, line in enumerate(text.splitlines(), 1):
        assert len(line) <= 100, f"line {i} exceeds 100 chars: {line}"
    if "--check" in sys.argv:
        current = target.read_text()
        if current != text:
            sys.exit(f"{target} is not byte-identical to the generator output; regenerate")
        print(f"{target}: byte-identical ({len(WEIGHTS)} weights)")
    else:
        target.write_text(text)
        print(f"wrote {target} ({len(WEIGHTS)} weights)")


if __name__ == "__main__":
    main()
