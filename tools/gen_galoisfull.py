#!/usr/bin/env python3
"""Iteration 21, stages G2/G3: generate `MaedaGaloisDim{6..10}Weights.lean`.

For each of the 30 weights with 6 <= dim S_k <= 10 the generated module proves
`MaedaWeightK.maeda_galois_full` (the Galois action of the charpoly of T_2 on
its complex roots is bijective, i.e. Gal = S_n) from the two certificates of
`research/iteration21/data/galoisfull_certs.json` (tools/galoisfull_certs.py):
a linear factor times an irreducible of degree n-1, and n-2 distinct linear
factors times an irreducible quadratic.  Irreducibility of each cofactor is a
reflected Rabin test with Bezout witnesses
(`MaedaGaloisFull.irreducible_of_rabin_bezout`: `zpgcd` overflows the kernel
stack at l ~ 5e6), the factorization itself one `decide +kernel` over
`znorm`/`mulLin`.

The literals of `P` are rendered by gen_maedan's own helpers, so `hcP` matches
them syntactically (chunked coefficients included).

`--prime 3` (Iteration 22, T1 T3-Galois): the T₃ twin — reads
`research/iteration22-t3-galois/data/t3_galoisfull_certs.json`
(galoisfull_certs.py --prime 3, charpolys pinned to the kernel-verified `P`
literals of MaedaT3Dim{6..10}Weights.lean), imports those T₃ dim files,
reopens their `MaedaT3Weight{K}` namespaces and emits
`MaedaT3GaloisDim{6..10}Weights.lean` + `MaedaT3GaloisFullAxCheck.lean`.  The
prime-2 output stays byte-identical.

Usage: gen_galoisfull.py [--prime {2,3}] [--only DIM] [--weight K] [--check]
`--weight` emits a single weight into the dimension's file (stage G2);
`--check` verifies byte-identical regeneration.
"""

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import gen_maedan as gm  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent

PRIME = int(sys.argv[sys.argv.index("--prime") + 1]) if "--prime" in sys.argv else 2
assert PRIME in (2, 3), PRIME

if PRIME == 2:
    DATA_PATH = "research/iteration21/data/galoisfull_certs.json"
    DIM_IMPORT = "MaedaDim{dim}Weights"
    NS = "MaedaWeight{k}"
    OUT = "MathProof/ModularForms/MaedaGaloisDim{dim}Weights.lean"
    AXCHECK = "MathProof/ModularForms/MaedaGaloisFullAxCheck.lean"
else:
    DATA_PATH = "research/iteration22-t3-galois/data/t3_galoisfull_certs.json"
    DIM_IMPORT = "MaedaT3Dim{dim}Weights"
    NS = "MaedaT3Weight{k}"
    OUT = "MathProof/ModularForms/MaedaT3GaloisDim{dim}Weights.lean"
    AXCHECK = "MathProof/ModularForms/MaedaT3GaloisFullAxCheck.lean"

DATA = json.loads((ROOT / DATA_PATH).read_text())

_T2 = PRIME == 2
HEADER = """import MathProof.ModularForms.{dim_import}
import MathProof.ModularForms.MaedaGaloisFull

/-!
# Maeda's conjecture in full{t3_title}, dimension {dim}: weights {klist}

Generated by `tools/gen_galoisfull.py{flag3}` from
`{data_path}` (byte-identical re-runs; do
not hand-edit).  For each weight, `maeda_galois_full` states that the Galois
group of the characteristic polynomial of `{op}` acts on its complex roots as
the full symmetric group, from a Frobenius `(n-1)`-cycle and a Frobenius
transposition (`MaedaGaloisFull.bijective_of_frobenius`).

Everything is light: `decide +kernel` certificates, no `set_option`, and no
module in this file is an ancestor of the heavy `MaedaGalois5Defs` chain.
-/

open Polynomial

attribute [local instance] Polynomial.Gal.splits_ℚ_ℂ

"""


def header(dim, klist):
    return HEADER.format(
        dim_import=DIM_IMPORT.format(dim=dim),
        t3_title="" if _T2 else ", T₃ twin",
        flag3="" if _T2 else " --prime 3",
        data_path=DATA_PATH,
        op="T₂" if _T2 else "T₃",
        dim=dim, klist=klist)


def coeff_expr(c):
    """A coefficient as a list entry: the same unit expression `P` carries."""
    chs = gm.term_chunks(c, "")
    if chs is None:
        return f"{c}"
    toks = gm.chunk_expr_tokens(chs)
    body = "\n      ".join(toks)
    return f"-({body})" if c < 0 else f"({body})"


def clist(cp):
    """Little-endian coefficient list of the big-endian charpoly `cp`."""
    return "[\n    " + ",\n    ".join(coeff_expr(c) for c in reversed(cp)) + "]"


def bezout(ell, f, h):
    """u, v with u * f + v * h = 1 over Z/ell (little-endian, entries in [0, ell))."""
    m = gm.msp

    def add(a, b, sign=1):
        r = [0] * max(len(a), len(b))
        for i, x in enumerate(a):
            r[i] = x % ell
        for i, x in enumerate(b):
            r[i] = (r[i] + sign * x) % ell
        return m.pnorm(r)

    def mul(a, b):
        return m.pnorm(m.pmul(a, b, ell)) if a and b else []

    r0, r1 = list(f), m.pnorm(list(h))
    u0, u1, v0, v1 = [1], [], [], [1]
    while r1:
        quo, rem = m.pdivmod(list(r0), list(r1), ell)
        quo = m.pnorm(list(quo))
        r0, r1 = r1, m.pnorm(list(rem))
        u0, u1 = u1, add(u0, mul(quo, u1), -1)
        v0, v1 = v1, add(v0, mul(quo, v1), -1)
    assert len(r0) == 1, "not coprime: the Rabin certificate fails"
    inv = pow(r0[0], -1, ell)
    u, v = mul([inv], u0), mul([inv], v0)
    assert add(mul(u, f), mul(v, h)) == [1]
    return u, v


def emit_cofactor(P, tag, ell, roots, gbar):
    """Rabin irreducibility of `gbar` + the factorization, under names `{tag}…`."""
    n = len(gbar) - 1
    F = (ell ** n).bit_length()
    assert gbar[-1] == 1
    h2s = []
    for q in gm.prime_divisors(n):
        h = gm.msp.psub_x(gm.reflected_powmod(ell, gbar, ell ** (n // q)), ell)
        h2s.append((q, *bezout(ell, gbar, h)))
    P(f"noncomputable def {tag} : List ℤ := {gm.lean_list(gbar, 2)}")
    P("")
    P(f"lemma {tag}_mon : (RabinCert.toPoly {ell} {tag}).Monic := by")
    P(f"  simp only [RabinCert.toPoly_nil, RabinCert.toPoly_cons, {tag}, mul_zero, add_zero]")
    P("  monicity!")
    P("")
    P(f"lemma {tag}_nd : (RabinCert.toPoly {ell} {tag}).natDegree = {n} := by")
    P(f"  simp only [RabinCert.toPoly_nil, RabinCert.toPoly_cons, {tag}, mul_zero, add_zero]")
    P("  compute_degree!")
    P("")
    P(f"lemma {tag}_hF : {ell} ^ {n} < 2 ^ {F} := by norm_num")
    P("")
    P(f"lemma {tag}_h1 : RabinCert.zpxw {ell} {tag} (RabinCert.bitsOf {F} ({ell} ^ {n})) [1]")
    P("      = [0, 1] :=")
    P("  by decide +kernel")
    P("")
    for q, u, v in h2s:
        P(f"lemma {tag}_h2_{q} : ∃ u v : List ℤ, RabinCert.znorm {ell}")
        P(f"      (RabinCert.zadd {ell} (RabinCert.zpmul {ell} u {tag}) (RabinCert.zpmul {ell} v")
        P(f"        (RabinCert.zpxwsubX {ell} {tag} {F} ({ell} ^ ({n} / {q}))))) = [1] :=")
        P(f"  ⟨{gm.lean_list(u, 2)},")
        P(f"    {gm.lean_list(v, 2)},")
        P("    by decide +kernel⟩")
        P("")
    P(f"lemma {tag}_h2 : ∀ q : ℕ, q.Prime → q ∣ {n} → ∃ u v : List ℤ, RabinCert.znorm {ell}")
    P(f"      (RabinCert.zadd {ell} (RabinCert.zpmul {ell} u {tag}) (RabinCert.zpmul {ell} v")
    P(f"        (RabinCert.zpxwsubX {ell} {tag} {F} ({ell} ^ ({n} / q))))) = [1] := by")
    P("  intro q hq hq2")
    P(f"  have hqb : q ≤ {n} := Nat.le_of_dvd (by norm_num) hq2")
    P("  interval_cases q")
    hq_qs = {q for q, _, _ in h2s}
    for q in range(n + 1):
        if q in hq_qs:
            P(f"  · exact {tag}_h2_{q}")
        elif gm.is_prime(q):
            P("  · exact absurd hq2 (by decide)")
        else:
            P("  · exact absurd hq (by decide)")
    P("")
    rlist = gm.lean_list(roots, 2)
    P(f"lemma {tag}_fact : RabinCert.znorm {ell} cP =")
    P(f"    RabinCert.znorm {ell} (MaedaGaloisFull.mulLin {ell}")
    P(f"      {rlist} {tag}) :=")
    P("  by decide +kernel")
    P("")
    P(f"lemma {tag}_dist : List.Pairwise")
    P(f"    (fun a b : ℤ => a % (({ell} : ℕ) : ℤ) ≠ b % (({ell} : ℕ) : ℤ))")
    P(f"    {rlist} :=")
    P("  by decide +kernel")
    P("")


def emit_weight(w):
    k, n = w["k"], w["dim"]
    out = []
    P = out.append
    P(f"/-! ### Weight {k} (dim {n}) -/")
    P(f"namespace {NS.format(k=k)}")
    P("")
    P("/-- The little-endian integer coefficients of `P`. -/")
    P(f"noncomputable def cP : List ℤ := {clist(w['charpoly'])}")
    P("")
    P("lemma hcP : P = MaedaGaloisFull.fromList cP := by")
    P("  simp only [P, cP, MaedaGaloisFull.fromList, C_neg]")
    P("  ring_nf")
    P("")
    e1, e2 = w["nm1"], w["transp"]
    emit_cofactor(P, "g1", e1["ell"], [e1["root"]], e1["gbar"])
    emit_cofactor(P, "g2", e2["ell"], e2["roots"], e2["hbar"])
    P("/-- **Maeda's conjecture in full in this weight**: `Gal = Sₙ`. -/")
    P("theorem maeda_galois_full :")
    P("    Function.Bijective (Gal.galActionHom (P.map (Int.castRingHom ℚ)) ℂ) :=")
    P(f"  haveI : Fact (Nat.Prime {e1['ell']}) := ⟨by norm_num⟩")
    P(f"  haveI : Fact (Nat.Prime {e2['ell']}) := ⟨by norm_num⟩")
    P(f"  MaedaGaloisFull.bijective_of_frobenius P_monic P_natDegree (by norm_num) maeda")
    for tag in ("g1", "g2"):
        ell = e1["ell"] if tag == "g1" else e2["ell"]
        d = n - 1 if tag == "g1" else 2
        P(f"    (MaedaGaloisFull.cycleType_of_cert hcP P_monic maeda.separable")
        P(f"      {tag}_fact {tag}_dist {tag}_mon")
        P(f"      (MaedaGaloisFull.irreducible_of_rabin_bezout {tag}_mon {tag}_nd (by norm_num)")
        P(f"        {tag}_hF {tag}_h1 {tag}_h2) {tag}_nd (by norm_num))")
    P("")
    P(f"end {NS.format(k=k)}")
    P("")
    return "\n".join(out) + "\n"


def emit_dim(dim, only_k=None):
    ws = sorted((w for w in DATA if w["dim"] == dim), key=lambda w: w["k"])
    if only_k is not None:
        ws = [w for w in ws if w["k"] == only_k]
    klist = ", ".join(str(w["k"]) for w in ws)
    return header(dim, klist) + "".join(emit_weight(w) for w in ws)


def emit_axcheck():
    """Opt-in audit: `#print axioms` for every weight (not in the root import)."""
    gname = "MaedaGaloisDim" if _T2 else "MaedaT3GaloisDim"
    imports = "".join(
        f"import MathProof.ModularForms.{gname}{d}Weights\n" for d in range(6, 11))
    body = imports + (
        f"\n/-! Axiom audit of {'Iteration 21' if _T2 else 'Iteration 22 (T₃ twin)'}"
        " (generated by `tools/gen_galoisfull.py"
        + ("" if _T2 else " --prime 3") + "`). -/\n\n")
    names = ["MaedaGaloisFull.bijective_of_frobenius", "MaedaGaloisFull.cycleType_of_cert",
             "FrobeniusCert.frob_cycleType_of_factorization"]
    names += [f"{NS.format(k=w['k'])}.maeda_galois_full" for w in DATA]
    return body + "".join(f"#print axioms {x}\n" for x in names)


def main():
    check = "--check" in sys.argv
    only = int(sys.argv[sys.argv.index("--only") + 1]) if "--only" in sys.argv else None
    weight = int(sys.argv[sys.argv.index("--weight") + 1]) if "--weight" in sys.argv else None
    if weight is not None:
        only = next(w["dim"] for w in DATA if w["k"] == weight)
    for dim in [only] if only else [6, 7, 8, 9, 10]:
        text = emit_dim(dim, weight)
        path = ROOT / OUT.format(dim=dim)
        if check:
            if not path.exists() or path.read_text() != text:
                print(f"NOT byte-identical: {path}")
                sys.exit(1)
            print(f"byte-identical: {path}")
        else:
            path.write_text(text)
            print(f"wrote {path} ({len(text.splitlines())} lines)")
    if weight is None and only is None:
        path = ROOT / AXCHECK
        if check:
            if not path.exists() or path.read_text() != emit_axcheck():
                print(f"NOT byte-identical: {path}")
                sys.exit(1)
        else:
            path.write_text(emit_axcheck())


if __name__ == "__main__":
    main()
