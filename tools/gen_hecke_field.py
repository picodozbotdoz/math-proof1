#!/usr/bin/env python3 -I
"""Generate the per-weight eigenvalue-containment instances (Hecke fields).

For every level-one weight 24 ≤ k ≤ 134 with 2 ≤ dim S_k ≤ 10 (54 weights)
this emits a light theorem consuming ONLY landed inputs — the generic layer
`HeckeField.eigenvalue_mem_adjoin` and the m = 3 rationality witnesses
`heckeT3_eq_aeval_rat_weightKK` of `HeckeRationalWeights.lean` (dims 6–10)
and `HeckeRationalSmallWeights.lean` (dims 2–5):

    theorem eigen_T3_mem_adjoin_weightKK {v} (hv : v ≠ 0) {μ}
        (hμ : heckeTPₗ ((KK : ℕ) : ℤ) Nat.prime_two v = μ • v) :
        ∃ w ∈ IntermediateField.adjoin ℚ ({μ} : Set ℂ),
          heckeTPₗ ((KK : ℕ) : ℤ) Nat.prime_three v = w • v

I.e. every nonzero T₂-eigenform is a T₃-eigenform with eigenvalue in the
eigenfield ℚ(λ₂) — the m = 3 instance of the T-Field track.  The T₂
hypothesis is stated through the canonical `heckeTPₗ k 2`, which is
definitionally the `T2` def of both source files (checked by the alignment
asserts below).  No literal tables, no kernel decides.

The weight lists are asserted against the `HeckeRatWeightKK` namespaces of
the two landed rationality files (the ground truth), so a re-run fails if
the upstream set changes.

Run:  python3 -I tools/gen_hecke_field.py            (write the file)
      python3 -I tools/gen_hecke_field.py --check    (byte-identity check)
"""

import re
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "MathProof/ModularForms/HeckeFieldWeights.lean"

SMALL_FILE = ROOT / "MathProof/ModularForms/HeckeRationalSmallWeights.lean"
BIG_FILE = ROOT / "MathProof/ModularForms/HeckeRationalWeights.lean"

# (weight, dim) — asserted against the landed files below.
SMALL = [(24, 2), (28, 2), (30, 2), (32, 2), (34, 2), (36, 3), (38, 2),
         (40, 3), (42, 3), (44, 3), (46, 3), (48, 4), (50, 3), (52, 4),
         (54, 4), (56, 4), (58, 4), (60, 5), (62, 4), (64, 5), (66, 5),
         (68, 5), (70, 5), (74, 5)]
BIG = [(72, 6), (76, 6), (78, 6), (80, 6), (82, 6), (84, 7), (86, 6),
       (88, 7), (90, 7), (92, 7), (94, 7), (96, 8), (98, 7), (100, 8),
       (102, 8), (104, 8), (106, 8), (108, 9), (110, 8), (112, 9), (114, 9),
       (116, 9), (118, 9), (120, 10), (122, 9), (124, 10), (126, 10),
       (128, 10), (130, 10), (134, 10)]

HEADER = """import MathProof.ModularForms.HeckeField
import MathProof.ModularForms.HeckeRationalWeights
import MathProof.ModularForms.HeckeRationalSmallWeights

/-!
# Hecke fields: per-weight eigenvalue containment `K ⊆ ℚ(λ₂)`

The m = 3 slice of the T-Field track: for each of the 54 verified Maeda
weights, every nonzero `T₂`-eigenform with eigenvalue `λ₂` is a `T₃`-
eigenform whose eigenvalue lies in the eigenfield
`IntermediateField.adjoin ℚ ({λ₂} : Set ℂ)` (read: `ℚ(λ₂)`).

Each instance is the generic spectral lemma
`HeckeField.eigenvalue_mem_adjoin` applied to the landed rationality
witness `heckeT3_eq_aeval_rat_weightKK` of `HeckeRationalWeights.lean`
(dims 6–10) / `HeckeRationalSmallWeights.lean` (dims 2–5); the `T₂`
hypothesis goes through the canonical `heckeTPₗ k Nat.prime_two`, which is
definitionally the `T2` def of both source files.  No literal tables and no
kernel decides — nothing for `AxCheckDecide` to audit beyond its parents.

This file is generated by `tools/gen_hecke_field.py` — regenerate, never
hand-edit (`python3 -I tools/gen_hecke_field.py --check` verifies
byte-identity).  Like `HeckeRationalSmallWeights` (one of its parents), it
is registered in the root `MathProof.lean` only and is NOT a
`defaultTargets`/CI item — see the note in `lakefile.toml`.
-/

open UpperHalfPlane ModularForm CuspForm Polynomial MaedaLevelOne
open scoped MatrixGroups
"""

BLOCK = """/-! ### Weight {w} (dim {d}) -/
namespace HeckeFieldWeight{w}

/-- **Eigenvalue containment at weight {w}**: every nonzero `T₂`-eigenform
with eigenvalue `λ₂` is a `T₃`-eigenform with eigenvalue in `ℚ(λ₂)`. -/
theorem eigen_T3_mem_adjoin_weight{w} {{v : CuspForm 𝒮ℒ (({w} : ℕ) : ℤ)}} (hv : v ≠ 0)
    {{μ : ℂ}} (hμ : heckeTPₗ (({w} : ℕ) : ℤ) Nat.prime_two v = μ • v) :
    ∃ w ∈ IntermediateField.adjoin ℚ ({{μ}} : Set ℂ),
      heckeTPₗ (({w} : ℕ) : ℤ) Nat.prime_three v = w • v :=
  HeckeField.eigenvalue_mem_adjoin HeckeRatWeight{w}.heckeT3_eq_aeval_rat_weight{w} hv hμ

end HeckeFieldWeight{w}
"""


def landed_namespaces(path):
    """The (weight, dim) pairs of the `HeckeRatWeightKK` sections in `path`."""
    text = path.read_text()
    secs = re.findall(r"### Weight (\d+) \(dim (\d+)\)", text)
    ns = re.findall(r"^namespace HeckeRatWeight(\d+)$", text, re.M)
    pairs = [(int(w), int(d)) for w, d in secs]
    assert [str(w) for w, _ in pairs] == ns, f"section/namespace misalignment: {path}"
    return pairs


def main():
    check = "--check" in sys.argv
    # Ground truth = the landed rationality files' sections.
    assert landed_namespaces(SMALL_FILE) == SMALL, "SMALL weight table drifted"
    assert landed_namespaces(BIG_FILE) == BIG, "BIG weight table drifted"
    # The T₂ bases of both parents are definitionally the canonical operator:
    # dims 2–5 define `T2` locally, dims 6–10 use `MaedaWeightKK.T2` (defined
    # in the MaedaDim{6..10}Weights files) — both as `heckeTPₗ k 2`.
    small_text = SMALL_FILE.read_text()
    big_text = BIG_FILE.read_text()
    dim_text = "".join(
        (ROOT / f"MathProof/ModularForms/MaedaDim{d}Weights.lean").read_text()
        for d in (6, 7, 8, 9, 10))
    for w, _ in SMALL:
        assert re.search(
            rf"noncomputable def T2 := heckeTPₗ \(\({w} : ℕ\) : ℤ\) Nat\.prime_two",
            small_text), f"non-canonical T2 def for weight {w} (small file)"
    for w, _ in BIG:
        assert f"Polynomial.aeval MaedaWeight{w}.T2" in big_text, \
            f"weight {w}: rationality theorem does not use MaedaWeight{w}.T2"
        assert re.search(
            rf"noncomputable def T2 := heckeTPₗ \(\({w} : ℕ\) : ℤ\) Nat\.prime_two",
            dim_text), f"non-canonical T2 def for weight {w} (dim files)"
    body = HEADER + "\n".join(
        BLOCK.format(w=w, d=d) for w, d in sorted(SMALL + BIG))
    if check:
        current = OUT.read_text()
        if current != body:
            sys.exit("HECKFIELDWEIGHTS DRIFTED: regenerate (tools/gen_hecke_field.py)")
        print("ok: HeckeFieldWeights.lean is up to date")
        return
    OUT.write_text(body)
    print(f"wrote {OUT} ({len(SMALL) + len(BIG)} weights)")


if __name__ == "__main__":
    main()
