#!/usr/bin/env python3 -I
"""Iteration-24 probe 3: extract integer representations of T₇ over the
monomials T₂^a T₃^b T₅^c (a+b+c ≤ n) at the 22 '{3,5}'-weights, and of T₅
over T₂^a T₃^b at the 12 dims-3–4 weights — the per-weight certificate
content of b3/b2.  Transform-tracking fraction-free elimination gives exact
multipliers; report digit sizes (feasibility cost model)."""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "research" / "iteration23" / "hecke-index"))
import g1_audit as G

gens = json.load(open(Path(__file__).resolve().parent / "probe_gens.json"))
ref = json.load(open(ROOT / "research/iteration23/hecke-index/index_data.json"))

def solve_rep(rows, target, n):
    """Integer c with sum c_i * rows[i] == target.  HNF-with-transform:
    reduce `rows` to a triangular basis (n rows) tracking unimodular U
    (basis = U · rows), then back-substitute target with exact divisions;
    coefficients over original rows = c_basis · U."""
    m = len(rows)
    M = [r[:] for r in rows]
    U = [[int(i == j) for j in range(m)] for i in range(m)]
    r0 = 0
    piv_cols = []
    for col in range(n):
        piv = next((i for i in range(r0, m) if M[i][col] != 0), None)
        if piv is None:
            continue
        M[r0], M[piv] = M[piv], M[r0]
        U[r0], U[piv] = U[piv], U[r0]
        for i in range(r0 + 1, m):
            while M[i][col] != 0:
                if M[r0][col] == 0 or abs(M[i][col]) < abs(M[r0][col]):
                    M[r0], M[i] = M[i], M[r0]
                    U[r0], U[i] = U[i], U[r0]
                q = M[i][col] // M[r0][col]
                M[i] = [a - q * b for a, b in zip(M[i], M[r0])]
                U[i] = [a - q * b for a, b in zip(U[i], U[r0])]
        piv_cols.append(col)
        r0 += 1
        if r0 == n:
            break
    assert r0 == n, "not full rank"
    t = target[:]
    cb = [0] * n
    for j in range(n):
        col = piv_cols[j]
        assert t[col] % M[j][col] == 0, "target not in lattice"
        q = t[col] // M[j][col]
        cb[j] = q
        t = [a - q * b for a, b in zip(t, M[j])]
    assert t == [0] * n, "residual"
    c = [0] * m
    for j in range(n):
        if cb[j]:
            c = [a + cb[j] * b for a, b in zip(c, U[j])]
    acc = [0] * n
    for i, ci in enumerate(c):
        if ci:
            acc = [a + ci * b for a, b in zip(acc, rows[i])]
    assert acc == target, "rep failed"
    return c

out = {}
for k in sorted(gens, key=int):
    chain = [s for s, _ in gens[k]["greedy"]]
    final = chain[-1]
    k = int(k); n = ref[str(k)]["dim"]
    mrows = G.basis_miller(k, n)
    M2m = G.op_matrix(k, 2, mrows)
    if final == [3, 5]:
        M3m = G.op_matrix(k, 3, mrows); M5m = G.op_matrix(k, 5, mrows)
        rows = []
        mem = {}
        def Xof(b, c5):
            key = (b, c5)
            if key not in mem:
                M = [[int(i == j) for j in range(n)] for i in range(n)]
                for _ in range(b): M = G.matmul(M, M3m)
                for _ in range(c5): M = G.matmul(M, M5m)
                mem[key] = M
            return mem[key]
        for b in range(n+1):
            for c5 in range(n+1-b):
                X = Xof(b, c5)
                for a in range(n-b-c5+1):
                    rows.append(G.matmul(G.matpow(M2m, a), X)[0][:])
        t7 = G.op_matrix(k, 7, mrows)[0][:]
        c = solve_rep(rows, t7, n)
        nz = [x for x in c if x]
        out[k] = {"type": "T7 in Z[T2,T3,T5]", "nmon": len(rows), "nz": len(nz),
                  "coef_digits": max(len(str(abs(x))) for x in nz)}
    elif n in (3, 4):
        M3m = G.op_matrix(k, 3, mrows)
        rows = [G.matmul(G.matpow(M2m, a), G.matpow(M3m, b))[0][:]
                for a in range(n) for b in range(n - a + 1)]
        # T5 in Z[T2,T3]? at dims<=4 quotient is generated by [T3] => yes
        t5 = G.op_matrix(k, 5, mrows)[0][:]
        c = solve_rep(rows, t5, n)
        nz = [x for x in c if x]
        out[k] = {"type": "T5 in Z[T2,T3]", "nmon": len(rows), "nz": len(nz),
                  "coef_digits": max(len(str(abs(x))) for x in nz)}
print(json.dumps(out, indent=1)[:3000])
Path(Path(__file__).resolve().parent, "probe_t7rep.json").write_text(json.dumps(out, indent=1))
print("written", len(out), "entries")
