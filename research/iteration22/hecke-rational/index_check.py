#!/usr/bin/env python3
"""Why the T3-in-Q[T2] witnesses have the denominators they have.

Run from the repository root (pure Python, ~1 min):
    python3 research/iteration22/hecke-rational/index_check.py

Observation, checked here for all 54 weights; NOT formalized in Lean.
Let f_1 .. f_n be the Miller basis of S_k(Z) (a_i(f_j) = delta_ij for i, j <= n)
and I_k = |det (a_{2^i}(f_j))| (0 <= i < n, 1 <= j <= n).  The duality
T_m = sum_j a_m(f_j) T_j makes T_1 .. T_n a Z-basis of the Hecke ring T, and
T_{2^i} is unitriangular over the powers of T_2, so I_k = [T : Z[T_2]].  Hence
the reduced denominator D of the g1_data.json witness divides I_k, with
equality for n <= 4, where T / Z[T_2] is cyclic, generated by T_3.

Asserted below: the Miller normalization, D | I_k at every weight, D = I_k
exactly when n <= 4, and the closed dim-2 / dim-3 witnesses.
"""
import json
from math import gcd
from fractions import Fraction as Fr
d=json.load(open('research/iteration22/hecke-rational/g1_data.json'))
N=516;B=3200
def sig(n,e): return sum(t**e for t in range(1,n+1) if n%t==0)
def pack(a):
    def go(l,h):
        if h-l==1: return a[l]
        m=(l+h)//2
        return go(l,m)+(go(m,h)<<(B*(m-l)))
    return go(0,len(a))
def unpack(v):
    v&=(1<<(B*N))-1
    def go(x,l,h):
        if h-l==1:return [x]
        m=(l+h)//2
        return go(x&((1<<(B*(m-l)))-1),l,m)+go(x>>(B*(m-l)),m,h)
    out=[];carry=0;half=1<<(B-1);full=1<<B
    for c in go(v,0,N):
        c+=carry
        if c>=half:c-=full;carry=1
        else:carry=0
        out.append(c)
    return out
def mul(a,b):return unpack(pack(a)*pack(b))
E4=[1]+[240*sig(n,3) for n in range(1,N)]
E6=[1]+[-504*sig(n,5) for n in range(1,N)]
c=mul(mul(E4,E4),E4);s=mul(E6,E6)
Delta=[(x-y)//1728 for x,y in zip(c,s)]
assert Delta[:6]==[0,1,-24,252,-1472,4830],Delta[:6]
assert Delta[12]==-370944
P=[[1]+[0]*(N-1)]
for j in range(1,12):P.append(mul(P[-1],Delta))
e={0:[1]+[0]*(N-1)}
def EP(a):
    if a not in e:e[a]=mul(EP(a-1),E4)
    return e[a]
def basis(k,dim):
    rows=[]
    for j in range(1,dim+1):
        w=k-12*j
        b=next(bb for bb in (0,1,2) if w-6*bb>=0 and (w-6*bb)%4==0)
        a=(w-6*b)//4
        f=mul(P[j],EP(a))
        for _ in range(b):f=mul(f,E6)
        rows.append(f)
    for j in range(dim-1,-1,-1):
        for i in range(j):
            c=rows[i][j+1]
            rows[i]=[x-c*y for x,y in zip(rows[i],rows[j])]
    return rows
def det(M):
    n=len(M);A=[[Fr(x) for x in r] for r in M];D=Fr(1)
    for c in range(n):
        p=next((r for r in range(c,n) if A[r][c]!=0),None)
        if p is None:return 0
        if p!=c:A[p],A[c]=A[c],A[p];D=-D
        D*=A[c][c]
        for r in range(c+1,n):
            f=A[r][c]/A[c][c]
            if f:A[r]=[x-f*y for x,y in zip(A[r],A[c])]
    return int(D)
res=[]
for k in sorted(d,key=int):
    r=d[k];n=r['dim'];kk=int(k)
    M=basis(kk,n)
    for i in range(n):
        for j in range(n):assert M[j][i+1]==int(i==j),(k,i,j)
    Idx=abs(det([[M[j][2**i] for j in range(n)] for i in range(n)]))
    D=r['D'];g=D
    for x in r['N']:g=gcd(g,abs(x))
    Dr=D//g
    res.append((kk,n,Dr,Idx))
    q=Idx//Dr if Idx%Dr==0 else None
    assert q is not None and (q == 1) == (n <= 4), (kk, n)
    print(f'k={kk} dim={n} D={Dr} I_k/D={q}')
    if n==2:
        f1,f2=M
        assert [Fr(x,D) for x in r['N']]==[f1[3],f2[3]]
        print(f'  T3 = {f1[3]} + ({f2[3]}) T2')
    if n==3:
        f1,f2,f3=M;c=f3[4]
        wit=[Fr(-(2**(kk-1))-f1[4],c),Fr(-f2[4],c),Fr(1,c)]
        assert wit==[Fr(x,D) for x in r['N']]
        print(f'  T3 = (T2^2 - 2^(k-1) - a4(f1) - a4(f2) T2) / ({c})')
print(f'{len(res)} weights: D divides I_k everywhere; D = I_k at {sum(x[3]==x[2] for x in res)}')
